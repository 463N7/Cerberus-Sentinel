#pragma once

/* Upstream's 27-prefix compatibility clue, not a product/model identity table.
 * Registry/vendor detail remains separately owned by the SD recon database. */
#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

static inline bool cerberus_ble_flock_oui_hint(const uint8_t nimble_address[6],
    uint8_t address_type)
{
    /* NimBLE stores the displayed address in reverse byte order. Types 0 and 2
     * are public/public identity; random/resolved-random never imply an OUI. */
    if (!nimble_address || (address_type != 0U && address_type != 2U) ||
        (nimble_address[5] & 3U)) return false;
    static const uint8_t prefixes[27][3] = {
        {0x58,0x8E,0x81},{0xCC,0xCC,0xCC},{0xEC,0x1B,0xBD},
        {0x90,0x35,0xEA},{0x04,0x0D,0x84},{0xF0,0x82,0xC0},
        {0x1C,0x34,0xF1},{0x38,0x5B,0x44},{0x94,0x34,0x69},
        {0xB4,0xE3,0xF9},{0x70,0xC9,0x4E},{0x3C,0x91,0x80},
        {0xD8,0xF3,0xBC},{0x80,0x30,0x49},{0x14,0x5A,0xFC},
        {0x74,0x4C,0xA1},{0x08,0x3A,0x88},{0x9C,0x2F,0x9D},
        {0x94,0x08,0x53},{0xE4,0xAA,0xEA},{0xF4,0x6A,0xDD},
        {0xF8,0xA2,0xD6},{0xE0,0x0A,0xF6},{0x00,0xF4,0x8D},
        {0xD0,0x39,0x57},{0xE8,0xD0,0xFC},{0xB4,0x1E,0x52},
    };
    for (size_t i = 0U; i < sizeof(prefixes) / sizeof(prefixes[0]); ++i)
        if (nimble_address[5] == prefixes[i][0] &&
            nimble_address[4] == prefixes[i][1] && nimble_address[3] == prefixes[i][2])
            return true;
    return false;
}
